export function t(key: string, lang: LanguageCode = 'en'): string {
  const langDict = TRANSLATIONS[lang] || TRANSLATIONS.en;
  return langDict[key] || TRANSLATIONS.en[key] || key;
}

const translationCache: Record<string, string> = {};

export async function tr(text: string, targetLang: LanguageCode): Promise<string> {
  if (!text || targetLang === 'en') return text;
  
  const cacheKey = `${targetLang}:${text}`;
  if (translationCache[cacheKey]) {
    return translationCache[cacheKey];
  }

  try {
    const url = `https://translate.googleapis.com/translate_a/single?client=gtx&sl=auto&tl=${targetLang}&dt=t&q=${encodeURIComponent(text)}`;
    const res = await fetch(url);
    if (!res.ok) throw new Error("Translation network error");
    const data = await res.json();
    if (data && data[0] && data[0][0] && data[0][0][0]) {
      const translated = data[0].map((item: unknown[]) => item[0]).join('');
      translationCache[cacheKey] = translated;
      return translated;
    }
  } catch {
    // Graceful fallback
  }
  return text;
}
